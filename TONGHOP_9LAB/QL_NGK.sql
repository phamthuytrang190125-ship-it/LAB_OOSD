--1. BANG NHA CUNG UNG
CREATE TABLE NhaCungUng
(
    MaNCU VARCHAR2(10) NOT NULL,
    TenNCU VARCHAR2(100) NOT NULL,
    DiaChi VARCHAR2(200) NOT NULL,
    DienThoai VARCHAR2(15) NOT NULL,
    CONSTRAINT PK_NhaCungUng PRIMARY KEY (MaNCU)
);

--2. BANG LOAI NUOC GIAI KHAT (Nhan Hieu)
CREATE TABLE LoaiNGK
(
    MaLoai VARCHAR2(10) NOT NULL,
    MaNCU VARCHAR2(10) NOT NULL,
    TenLoai VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_LoaiNGK PRIMARY KEY (MaLoai),
    CONSTRAINT FK_LoaiNGK_NCU FOREIGN KEY (MaNCU) REFERENCES NhaCungUng(MaNCU)
);

--3. BANG NUOC GIAI KHAT
CREATE TABLE NuocGiaiKhat
(
    MaNGK VARCHAR2(10) NOT NULL,
    MaLoai VARCHAR2(10) NOT NULL,
    TenNGK VARCHAR2(100) NOT NULL,
    DonViTinh VARCHAR2(20) NOT NULL,
    SoLuongTon INT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_NuocGiaiKhat PRIMARY KEY (MaNGK),
    CONSTRAINT FK_NGK_Loai FOREIGN KEY (MaLoai) REFERENCES LoaiNGK(MaLoai),
    CONSTRAINT CK_NGK_TonKho CHECK (SoLuongTon >= 0)
);

--4. BANG NHAN VIEN
CREATE TABLE NhanVien
(
    MaNV VARCHAR2(10) NOT NULL,
    TenNV VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_NhanVien PRIMARY KEY (MaNV)
);

--5. BANG KHACH HANG
CREATE TABLE KhachHang
(
    MaKH VARCHAR2(10) NOT NULL,
    TenKH VARCHAR2(100) NOT NULL,
    LoaiKhach VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_KhachHang PRIMARY KEY (MaKH),
    CONSTRAINT CK_KhachHang_Loai CHECK (LoaiKhach IN ('Khach quen', 'Khach vang lai'))
);

--6. BANG DON DAT HANG
CREATE TABLE DonDatHang
(
    SoDDH VARCHAR2(10) NOT NULL,
    MaNCU VARCHAR2(10) NOT NULL,
    MaNV VARCHAR2(10) NOT NULL,
    NgayDat DATE NOT NULL,
    NgayNhan DATE,
    CONSTRAINT PK_DonDatHang PRIMARY KEY (SoDDH),
    CONSTRAINT FK_DDH_NCU FOREIGN KEY (MaNCU) REFERENCES NhaCungUng(MaNCU),
    CONSTRAINT FK_DDH_NV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV)
);

--7. BANG CHI TIET DON DAT HANG
CREATE TABLE ChiTietDDH
(
    SoDDH VARCHAR2(10) NOT NULL,
    MaNGK VARCHAR2(10) NOT NULL,
    SoLuongDat INT NOT NULL,
    CONSTRAINT PK_ChiTietDDH PRIMARY KEY (SoDDH, MaNGK),
    CONSTRAINT FK_CTDDH_DDH FOREIGN KEY (SoDDH) REFERENCES DonDatHang(SoDDH),
    CONSTRAINT FK_CTDDH_NGK FOREIGN KEY (MaNGK) REFERENCES NuocGiaiKhat(MaNGK),
    CONSTRAINT CK_CTDDH_SoLuong CHECK (SoLuongDat > 0)
);

--8. BANG PHIEU GIAO HANG
CREATE TABLE PhieuGiaoHang
(
    SoPGH VARCHAR2(10) NOT NULL,
    SoDDH VARCHAR2(10) NOT NULL,
    NgayGiao DATE NOT NULL,
    TongTien NUMBER(18,2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PhieuGiaoHang PRIMARY KEY (SoPGH),
    CONSTRAINT FK_PGH_DDH FOREIGN KEY (SoDDH) REFERENCES DonDatHang(SoDDH),
    CONSTRAINT CK_PGH_TongTien CHECK (TongTien >= 0)
);

--9. BANG CHI TIET PHIEU GIAO HANG
CREATE TABLE ChiTietPGH
(
    SoPGH VARCHAR2(10) NOT NULL,
    MaNGK VARCHAR2(10) NOT NULL,
    SoLuongGiao INT NOT NULL,
    SoTien NUMBER(18,2) NOT NULL,
    CONSTRAINT PK_ChiTietPGH PRIMARY KEY (SoPGH, MaNGK),
    CONSTRAINT FK_CTPGH_PGH FOREIGN KEY (SoPGH) REFERENCES PhieuGiaoHang(SoPGH),
    CONSTRAINT FK_CTPGH_NGK FOREIGN KEY (MaNGK) REFERENCES NuocGiaiKhat(MaNGK),
    CONSTRAINT CK_CTPGH_SoLuong CHECK (SoLuongGiao > 0),
    CONSTRAINT CK_CTPGH_SoTien CHECK (SoTien >= 0)
);

--10. BANG HOA DON
CREATE TABLE HoaDon
(
    SoHD VARCHAR2(10) NOT NULL,
    MaKH VARCHAR2(10) NOT NULL,
    MaNV VARCHAR2(10) NOT NULL,
    NgayLap DATE DEFAULT SYSDATE NOT NULL,
    TongTien NUMBER(18,2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_HoaDon PRIMARY KEY (SoHD),
    CONSTRAINT FK_HD_KH FOREIGN KEY (MaKH) REFERENCES KhachHang(MaKH),
    CONSTRAINT FK_HD_NV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT CK_HD_TongTien CHECK (TongTien >= 0)
);

--11. BANG CHI TIET HOA DON
CREATE TABLE ChiTietHoaDon
(
    SoHD VARCHAR2(10) NOT NULL,
    MaNGK VARCHAR2(10) NOT NULL,
    SoLuong INT NOT NULL,
    DonGia NUMBER(18,2) NOT NULL,
    CONSTRAINT PK_ChiTietHoaDon PRIMARY KEY (SoHD, MaNGK),
    CONSTRAINT FK_CTHD_HD FOREIGN KEY (SoHD) REFERENCES HoaDon(SoHD),
    CONSTRAINT FK_CTHD_NGK FOREIGN KEY (MaNGK) REFERENCES NuocGiaiKhat(MaNGK),
    CONSTRAINT CK_CTHD_SoLuong CHECK (SoLuong > 0),
    CONSTRAINT CK_CTHD_DonGia CHECK (DonGia >= 0)
);

--12. BANG PHIEU HEN
CREATE TABLE PhieuHen
(
    SoPhieuHen VARCHAR2(10) NOT NULL,
    SoHD VARCHAR2(10) NOT NULL,
    NgayHen DATE NOT NULL,
    CONSTRAINT PK_PhieuHen PRIMARY KEY (SoPhieuHen),
    CONSTRAINT FK_PH_HD FOREIGN KEY (SoHD) REFERENCES HoaDon(SoHD)
);

--13. BANG CHI TIET PHIEU HEN
CREATE TABLE ChiTietPhieuHen
(
    SoPhieuHen VARCHAR2(10) NOT NULL,
    MaNGK VARCHAR2(10) NOT NULL,
    SoLuongHen INT NOT NULL,
    CONSTRAINT PK_ChiTietPhieuHen PRIMARY KEY (SoPhieuHen, MaNGK),
    CONSTRAINT FK_CTPH_PH FOREIGN KEY (SoPhieuHen) REFERENCES PhieuHen(SoPhieuHen),
    CONSTRAINT FK_CTPH_NGK FOREIGN KEY (MaNGK) REFERENCES NuocGiaiKhat(MaNGK),
    CONSTRAINT CK_CTPH_SoLuong CHECK (SoLuongHen > 0)
);

--14. BANG PHIEU GHI NO
CREATE TABLE PhieuGhiNo
(
    SoPhieuNo VARCHAR2(10) NOT NULL,
    MaKH VARCHAR2(10) NOT NULL,
    MaNV VARCHAR2(10) NOT NULL,
    NgayLap DATE DEFAULT SYSDATE NOT NULL,
    SoTienNo NUMBER(18,2) NOT NULL,
    NgayDuKienTra DATE NOT NULL,
    LyDo VARCHAR2(255) NOT NULL,
    CONSTRAINT PK_PhieuGhiNo PRIMARY KEY (SoPhieuNo),
    CONSTRAINT FK_PGN_KH FOREIGN KEY (MaKH) REFERENCES KhachHang(MaKH),
    CONSTRAINT FK_PGN_NV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT CK_PGN_SoTien CHECK (SoTienNo > 0)
);


